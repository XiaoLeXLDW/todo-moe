import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const glass = 'apps/mobile/modules/moe-glass/android/src/main/assets/moe-glass';
const appLicenseDirectory = path.join(root, 'apps/mobile/modules/moe-glass/android/src/main/assets/todo-moe-legal');
fs.mkdirSync(appLicenseDirectory, { recursive: true });
fs.writeFileSync(path.join(appLicenseDirectory, 'LICENSE-AGPL-3.0.txt'), read('LICENSE'));
const notices = [
  { title: 'Todo Moe / Mindwtr · AGPL-3.0-only', text: read('LICENSE'), source: 'LICENSE' },
  ...['Apache-2.0.txt', 'NOTICE.txt', 'THIRD_PARTY.md', 'SUKISU-COMPOSE-SOURCES.md'].map(file => ({
    title: `Moe Glass · ${file}`, text: read(`${glass}/${file}`), source: `${glass}/${file}`,
  })),
];
const visited = new Set();
const missing = [];
function resolvePackage(name, from) {
  if (name === '@mindwtr/core') return path.join(root, 'packages/core');
  for (let folder = from; ; folder = path.dirname(folder)) {
    const candidate = path.join(folder, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (folder === path.dirname(folder)) return null;
  }
  return null;
}
function visit(folder) {
  const pkg = JSON.parse(fs.readFileSync(path.join(folder, 'package.json'), 'utf8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (visited.has(key)) return;
  visited.add(key);
  const files = fs.readdirSync(folder).filter(file => /^(licen[sc]e|copying|notice)([.-]|$)/i.test(file) && fs.statSync(path.join(folder, file)).isFile());
  if (files.length) notices.push({ title: `${key} · ${typeof pkg.license === 'string' ? pkg.license : 'see notice'}`, source: key, text: files.map(file => `${file}\n\n${fs.readFileSync(path.join(folder, file), 'utf8').replace(/\r\n/g, '\n')}`).join('\n\n') });
  else missing.push(key);
  for (const name of Object.keys(pkg.dependencies ?? {}).sort()) {
    const resolved = resolvePackage(name, folder);
    if (resolved) visit(resolved);
    else missing.push(`${name} (not installed)`);
  }
}
visit(path.join(root, 'apps/mobile'));
const output = 'apps/mobile/moe/legal/notices.generated.ts';
fs.mkdirSync(path.dirname(path.join(root, output)), { recursive: true });
fs.writeFileSync(path.join(root, output), `// Generated by scripts/moe/generate-license-notices.mjs. Preserve license text verbatim.\nexport const bundledNotices = ${JSON.stringify(notices, null, 2)} as const;\nexport const noticeCoverage = ${JSON.stringify({ scope: 'Installed mobile runtime dependency declarations, plus copied glass sources. Native transitive libraries may carry their own embedded notices. This is not an exhaustive binary license audit.', missing: [...new Set(missing)].sort() }, null, 2)} as const;\n`);
console.log(`Bundled ${notices.length} notices; ${missing.length} packages without root notice files (recorded in coverage).`);
